import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { Wallet } from 'ethers';
import { fmtMicro, parseMicro } from '../src/money';

/**
 * Builds agents/data-testnet from agents/data for on-chain runs on Arc testnet:
 *  - every amount is divided by 1,000 (the faucet gives ~20 USDC, not thousands)
 *  - the five demo vendors and the attacker get fresh addresses (random keys, kept in a gitignored file), instead of the placeholder zero-padded ones
 * Run: npx tsx scripts/make-testnet-data.ts
 */
const SRC = join(__dirname, '..', 'data');
const OUT = join(__dirname, '..', 'data-testnet');
// Vendor and attacker wallets are FRESH RANDOM keys, saved to a gitignored file so they stay recoverable.
// Never derive demo wallets from a public mnemonic: bots sweep those addresses on every chain within seconds
// (an earlier version of this script did, and a payment was swept).
const KEYS = join(__dirname, '..', '.testnet-vendor-keys.local.json');
const keys: Record<string, string> = existsSync(KEYS) ? JSON.parse(readFileSync(KEYS, 'utf8')) : {};
const wallet = (name: string): string => {
  if (!keys[name]) keys[name] = Wallet.createRandom().privateKey;
  return new Wallet(keys[name]).address.toLowerCase();
};

const WALLETS: Record<string, string> = {
  '0x71c4000000000000000000000000000000009ae2': wallet('northwind'),
  '0x44af0000000000000000000000000000000002d9': wallet('lumen'),
  '0xb90d0000000000000000000000000000000077c1': wallet('lumen-new'),
  '0x5d1200000000000000000000000000000000ab40': wallet('orbit'),
  '0x3e8b00000000000000000000000000000000c5d7': wallet('kestrel'),
  '0xdead00000000000000000000000000000000beef': wallet('attacker'),
};
writeFileSync(KEYS, JSON.stringify(keys, null, 2));

const scaleAmount = (s: string): string => {
  const micro = parseMicro(s);
  if (micro === null) throw new Error(`cannot scale ${s}`);
  const scaled = micro / 1000n;
  if (scaled * 1000n !== micro) throw new Error(`${s} does not divide evenly`);
  const whole = scaled / 1_000_000n;
  const frac = (scaled % 1_000_000n).toString().padStart(6, '0').replace(/0+$/, '').padEnd(2, '0');
  return `${whole}.${frac}`;
};

const swapWallets = (t: string) => Object.entries(WALLETS).reduce((acc, [a, b]) => acc.split(a).join(b), t);
// "125.00", "1237.50": any decimal token. Hex, dates and quantities contain no such token.
const scaleText = (t: string) => swapWallets(t).replace(/\b\d+\.\d{2}\b/g, (m) => scaleAmount(m));

mkdirSync(join(OUT, 'invoices'), { recursive: true });
cpSync(join(SRC, 'invoices'), join(OUT, 'invoices'), { recursive: true });
for (const f of readdirSync(join(OUT, 'invoices'))) {
  const p = join(OUT, 'invoices', f);
  writeFileSync(p, scaleText(readFileSync(p, 'utf8')));
}

const ledger = JSON.parse(readFileSync(join(SRC, 'ledger.json'), 'utf8'));
const AMOUNT_KEYS = new Set(['perTxLimit', 'balance', 'reserve', 'committed', 'rate', 'expectedTotal', 'remaining', 'total']);
const walk = (o: any): any => {
  if (Array.isArray(o)) return o.map(walk);
  if (o && typeof o === 'object') return Object.fromEntries(Object.entries(o).map(([k, v]) => [k, AMOUNT_KEYS.has(k) && typeof v === 'string' && v !== '0' ? scaleAmount(v) : walk(v)]));
  return typeof o === 'string' ? swapWallets(o) : o;
};
const out = walk(ledger);
out._note = 'Testnet-scale demo ledger generated by scripts/make-testnet-data.ts: amounts /1000, fresh fresh random test wallets (keys kept locally).';
writeFileSync(join(OUT, 'ledger.json'), JSON.stringify(out, null, 2) + '\n');
console.log('wrote', OUT);
console.log('vendors:', out.vendors.map((v: any) => `${v.name} ${v.wallet}`).join('\n         '));
console.log('limit:', out.perTxLimit, '| treasury:', out.treasury.balance, 'reserve', out.treasury.reserve, '| fmt check:', fmtMicro(parseMicro('9.8')!));
